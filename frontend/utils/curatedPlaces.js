// Get curated places based on destination and theme
export const getCuratedPlaces = (destination, theme) => {
  // Normalize destination name
  const normalizedDest = Object.keys(curatedPlaces).find(key => 
    destination.toLowerCase().includes(key.toLowerCase().split(',')[0])
  );

  if (!normalizedDest) {
    return [];
  }

  const destPlaces = curatedPlaces[normalizedDest];
  
  // Get places for the specific theme
  if (theme && destPlaces[theme]) {
    return destPlaces[theme];
  }

  // If no theme or theme not found, return all places for destination
  return Object.values(destPlaces).flat();
};
